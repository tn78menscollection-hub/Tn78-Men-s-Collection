import { getMediaAssets } from "./mediaAssets";

export function getProductImageUrl(
  slug?: string,
  category?: string,
  rawUrl?: string
): string | undefined {
  // 1. Check if admin configured custom image overrides in Visual Media / Admin Manager
  if (typeof window !== "undefined") {
    try {
      const overrides = getMediaAssets().productOverrides;
      if (slug && overrides[slug]?.length && overrides[slug][0]) {
        return overrides[slug][0];
      }
    } catch {}
  }

  if (
    rawUrl &&
    (rawUrl.startsWith("http://") ||
      rawUrl.startsWith("https://") ||
      rawUrl.startsWith("/") ||
      rawUrl.startsWith("data:"))
  ) {
    return rawUrl;
  }

  if (slug && PRODUCT_IMAGE_MAP[slug]) {
    return PRODUCT_IMAGE_MAP[slug];
  }

  if (category) {
    const cleanCat = category.toLowerCase().trim();
    if (CATEGORY_IMAGE_MAP[cleanCat]) {
      return CATEGORY_IMAGE_MAP[cleanCat];
    }
  }

  return undefined;
}
